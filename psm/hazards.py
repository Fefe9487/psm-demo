HAZARD_STATEMENT_LABELS = {
    code: label for _, items in HAZARD_STATEMENT_GROUPS for code, label in items
}
_H_CODE = re.compile(r"(?<![A-Z])H\d{3}[A-Z]?(?![A-Z])", re.IGNORECASE)


def hazard_display_labels(value: str | None) -> list[str]:
    """Return readable labels while keeping unknown SDS codes visible."""
    codes = dict.fromkeys(match.upper() for match in _H_CODE.findall(value or ""))
    return [f"{HAZARD_STATEMENT_LABELS.get(code, code)}（{code}）" for code in codes]
